from PIL import Image, ImageDraw

from pgot.eval.natural_object_selection import (
    SYSTEM, aggregate, annotated_queries, candidates_from_caption, crop,
    decode_segments, digest, fixed_correspondence, parse_selection,
    query_kinds, score_query, selector_messages,
)

VERSION = "natural-owner-selection-v1"


def write_json(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False))
    temporary.replace(path)


def file_digest(path):
    import hashlib
    value = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024*1024), b""):
            value.update(block)
    return value.hexdigest()


def jsonl(path):
    return [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]


def checkpoint_signature(folder):
    folder=Path(folder)
    index=folder/"model.safetensors.index.json"
    names=sorted(set(json.loads(index.read_text())["weight_map"].values()))
    return dict(config_sha256=file_digest(folder/"config.json"),index_sha256=file_digest(index),
                shards=[dict(name=name,path=str((folder/name).resolve()),
                             bytes=(folder/name).stat().st_size,mtime_ns=(folder/name).stat().st_mtime_ns)
                        for name in names])


def prepare(args):
    out = Path(args.output_dir)
    config = dict(version=VERSION, model_path=str(Path(args.model_path).resolve()),
                  model_config_sha256=file_digest(Path(args.model_path)/"config.json"),
                  checkpoint_index_sha256=file_digest(Path(args.model_path)/"model.safetensors.index.json"),
                  annotations_sha256=file_digest(args.annotations), captions_sha256=file_digest(args.captions),
                  caption_summary_sha256=file_digest(args.caption_summary),
                  custom_queries_sha256=file_digest(args.queries) if args.queries else None,
                  eval_size=args.eval_size, seed=args.seed, image_ids=args.image_ids,
                  max_images=args.max_images, presence_iou=args.presence_iou,
                  dtype=args.dtype,max_objects=args.max_objects,max_caption_tokens=args.max_caption_tokens,
                  cache_bundles=args.cache_bundles,checkpoint_signature=checkpoint_signature(args.model_path),
                  train_annotations_sha256=file_digest(args.train_annotations),
                  query_source="custom_requests" if args.queries else "independent_pix2cap_annotation_descriptions")
    fingerprint = digest(config)
    if (out/"manifest.json").exists():
        previous = json.loads((out/"manifest.json").read_text())
        if previous["fingerprint"] != fingerprint:
            raise ValueError("Existing experiment differs; choose a new OUTPUT_DIR")
        for sample in previous["samples"]:
            if not (out/"gt"/f"{sample['image_id']}.npz").exists():
                raise ValueError("Incomplete GT cache: use a fresh output directory")
        print("Preparation already complete; identical manifest reused.", flush=True)
        return
    summary = json.loads(Path(args.caption_summary).read_text())
    if Path(summary["ckpt"]).resolve() != Path(args.model_path).resolve():
        raise ValueError("AR captions were generated by another checkpoint")
    if summary.get("caption_mode") != "autoregressive":
        raise ValueError("Selection requires image-only AR captions, not GT/teacher-forced captions")
    records = jsonl(args.annotations)
    source_ids = [int(r["image_id"]) for r in records]
    if len(set(source_ids)) != len(source_ids):
        raise ValueError("Duplicate annotation image IDs")
    caption_records = jsonl(args.captions)
    captions = {int(r["image_id"]): r for r in caption_records}
    if len(captions) != len(caption_records):
        raise ValueError("Duplicate AR caption image IDs")
    custom = jsonl(args.queries) if args.queries else None
    wanted = [int(i) for i in args.image_ids.split(",")] if args.image_ids else None
    if custom is not None:
        custom_images = {int(q["image_id"]) for q in custom}
        if custom_images - set(source_ids):
            raise ValueError("Custom query references an image outside annotations")
        records = [r for r in records if int(r["image_id"]) in custom_images]
    if wanted is not None:
        by_id = {int(r["image_id"]): r for r in records}
        if set(wanted)-by_id.keys() or len(set(wanted)) != len(wanted):
            raise ValueError("Missing/duplicate requested image IDs")
        records = [by_id[i] for i in wanted]
    if args.max_images is not None:
        records = records[:args.max_images]
    samples, queries, invisible, empty_descriptions = [], [], 0, 0
    for record in records:
        iid = int(record["image_id"])
        if iid not in captions:
            raise ValueError(f"Missing AR caption for image {iid}; never drop failed images")
        with Image.open(record["panoptic_mask_path"]) as image:
            gt_labels = decode_segments(crop(image, args.eval_size, nearest=True))
        objects = []
        for segment in record["segments"]:
            if not segment.get("is_thing", True):
                continue
            sid = int(segment["segment_id"])
            if not np.any(gt_labels == sid):
                invisible += 1
                continue
            if not str(segment.get("description", "")).strip():
                empty_descriptions += 1
                raise ValueError(f"Missing independent query description for {iid}/{sid}")
            objects.append(dict(segment_id=sid, category=segment["category"], description=segment["description"]))
        if len({o["segment_id"] for o in objects}) != len(objects):
            raise ValueError("Duplicate GT segment identities")
        targets = np.stack([gt_labels == o["segment_id"] for o in objects]) if objects else np.zeros((0,args.eval_size,args.eval_size),bool)
        gt_dir=out/"gt"; gt_dir.mkdir(parents=True,exist_ok=True)
        np.savez_compressed(gt_dir/f"{iid}.npz", targets=targets)
        generated = captions[iid]
        text, count = generated["text"], int(generated["ovt_count"])
        if text.count("<ovt>") != count:
            raise ValueError("AR caption/OVT count mismatch")
        candidates = candidates_from_caption(text, count, iid, args.seed)
        sample_queries = annotated_queries(iid, objects)
        if custom is not None:
            sample_queries = []
            for q in custom:
                if int(q["image_id"]) != iid:
                    continue
                sid = int(q["target_segment_id"])
                base = next((q0 for q0 in annotated_queries(iid, objects) if q0["target_segment_id"] == sid), None)
                if base is None:
                    raise ValueError(f"Request target missing/cropped out: {iid}/{sid}")
                request = q["request"]
                if not isinstance(request,str) or not request.strip():
                    raise ValueError("Empty request")
                sample_queries.append(dict(base, id=digest([iid,sid,request]), request=request,
                                           query_types=q.get("query_types",query_kinds(request)),
                                           ambiguous_annotation=bool(q.get("ambiguous",False))))
        samples.append(dict(image_id=iid,image_path=record["image_path"],caption=text,
                            caption_sha256=digest(text),ovt_count=count,candidates=candidates,gt_objects=objects))
        queries.extend(sample_queries)
    if not queries or len({q["id"] for q in queries}) != len(queries):
        raise ValueError("No queries or duplicate query identities")
    train_ids={int(r["image_id"]) for r in jsonl(args.train_annotations)}
    overlap=sorted(train_ids & {s["image_id"] for s in samples})
    protocol=dict(selector_image_input=False,selector_gt_input=False,selector_region_coordinates=False,
                  regenerated_ar_captions=False,generated_descriptions_truncated=False,
                  candidate_ids="deterministically shuffled opaque IDs; same order in both conditions",
                  matching="class-compatible max-cardinality one-to-one IoU matching, fixed independently of requests/selector",
                  presence_iou=args.presence_iou,success_iou_thresholds=[.5,.75],
                  missing_target_and_invalid_selection="included; IoU zero for no selected region",
                  ambiguous_queries="retained and separately reported; not silently removed",
                  query_type_groups="overlapping lexical diagnostics, not human-verified semantic labels",
                  not_refcoco_benchmark=True,source_manifest_images=len(source_ids),selected_images=len(samples),
                  cropped_invisible_instances=invisible,empty_descriptions=empty_descriptions,
                  train_image_overlap_count=len(overlap),train_image_overlap_ids=overlap,
                  train_annotations_sha256=file_digest(args.train_annotations),
                  limitations="Annotation descriptions may be ambiguous or inaccurate. Custom smoke is a curated demonstration, not representative performance.")
    write_json(out/"manifest.json",dict(config=config,fingerprint=fingerprint,protocol=protocol,samples=samples,queries=queries))
    print(f"Prepared {len(samples)} images / {len(queries)} independent requests; train overlap={len(overlap)}.",flush=True)


def manifest(args):
    root=Path(args.output_dir)
    value=json.loads((root/"manifest.json").read_text())
    if value["config"]["model_path"] != str(Path(args.model_path).resolve()):
        raise ValueError("Checkpoint/manifest mismatch")
    if value["config"]["checkpoint_signature"] != checkpoint_signature(args.model_path):
        raise ValueError("Checkpoint files changed after preparation")
    for key in ("dtype","eval_size","max_objects","max_caption_tokens","cache_bundles","seed","presence_iou"):
        if value["config"][key]!=getattr(args,key):
            raise ValueError(f"CLI/manifest extraction configuration mismatch: {key}")
    return root,value


def extracted(root,sample,fingerprint):
    folder=root/"owners"/str(sample["image_id"])
    if not (folder/"metadata.json").exists():
        return False
    meta=json.loads((folder/"metadata.json").read_text())
    if meta["fingerprint"] != fingerprint or meta["caption_sha256"] != sample["caption_sha256"]:
        raise ValueError("Owner-cache provenance mismatch")
    return (folder/"prediction.npz").is_file()


def extract(args):
    import torch
    from pgot.eval.eval_recon_oracles import load_model_and_tokenizer
    from pgot.eval.pgot_inference import pgot_forward_eval
    from pgot.model.pgot_utils import build_pred_mask_ovt_owner_eval
    root,m=manifest(args)
    pending=[s for s in m["samples"] if not extracted(root,s,m["fingerprint"])]
    if not pending:
        print("All immutable AR owner maps already cached; no DeOR load needed.",flush=True)
        return
    torch.set_num_threads(args.cpu_threads)
    torch.manual_seed(args.seed)
    model,tokenizer,device,_=load_model_and_tokenizer(args)
    checkpoint_keys=set(json.loads((Path(args.model_path)/"model.safetensors.index.json").read_text())["weight_map"])
    missing=sorted(set(model.state_dict())-checkpoint_keys)
    unexpected=sorted(checkpoint_keys-set(model.state_dict()))
    parameters=dict(model.named_parameters(remove_duplicate=False))
    saved_parameter_ids={id(parameters[k]) for k in checkpoint_keys if k in parameters}
    missing_tied_aliases=sorted(k for k in missing if k in parameters and id(parameters[k]) in saved_parameter_ids)
    missing_parameters=sorted(k for k in missing if k in parameters and k not in missing_tied_aliases)
    missing_buffers=sorted(k for k in missing if k not in parameters)
    if missing_parameters or unexpected:
        raise ValueError(f"Checkpoint did not restore model parameters: missing={missing_parameters}, unexpected={unexpected}")
    write_json(root/"deor_model_info.json",dict(checkpoint=m["config"]["model_path"],
               missing_parameters=missing_parameters,missing_buffers=missing_buffers,
               missing_tied_aliases=missing_tied_aliases,unexpected=unexpected,
               dtype=args.dtype,all_four_special_token_ids_registered=True))
    print(f"Checkpoint parameter audit: missing_parameters={missing_parameters}, missing_buffers={missing_buffers}, tied_aliases={missing_tied_aliases}, unexpected={unexpected}",flush=True)
    # Own-caption conditioning must use the same markers as training/run_eval.
    for name,token in (("ovt","<ovt>"),("scene_end","<scene_end>"),("thing","<thing>"),("stuff","<stuff>")):
        setattr(model,f"pgot_{name}_token_id",tokenizer.convert_tokens_to_ids(token))
    towers=model.get_vision_tower_aux_list()
    for sample in pending:
        iid=sample["image_id"]
        with Image.open(sample["image_path"]) as im:
            image=crop(im.convert("RGB"),m["config"]["eval_size"])
        folder=root/"owners"/str(iid);folder.mkdir(parents=True,exist_ok=True)
        image.save(folder/"image.png")
        count=sample["ovt_count"]
        if count > args.max_objects:
            raise ValueError("Too many AR owners; never truncate")
        result=None
        if count:
            ids=torch.tensor(tokenizer.encode(sample["caption"],add_special_tokens=False))[None]
            positions=(ids[0]==tokenizer.convert_tokens_to_ids("<ovt>")).nonzero().flatten()
            if len(positions)!=count or ids.shape[1] > args.max_caption_tokens:
                raise ValueError("Caption token/owner limit mismatch; never truncate descriptions")
            valid=torch.zeros((1,args.max_objects),dtype=torch.bool)
            packed=torch.zeros((1,args.max_objects),dtype=torch.long)
            valid[0,:count]=True;packed[0,:count]=positions
            things=torch.zeros_like(valid)
            for candidate in sample["candidates"]:
                if candidate["slot_index"] is not None:
                    things[0,candidate["slot_index"]]=True
            with torch.inference_mode():
                result=pgot_forward_eval(model,images=towers[0].image_processor.preprocess(image,return_tensors="pt")["pixel_values"],
                    target_images=(towers[1] if len(towers)>1 else towers[0]).image_processor.preprocess(image,return_tensors="pt")["pixel_values"],
                    caption_input_ids=ids,caption_attention_mask=torch.ones_like(ids,dtype=torch.bool),
                    ovt_positions_in_caption=packed,ovt_valid_mask=valid)
                prediction=build_pred_mask_ovt_owner_eval(result["ovt_object_probs"],result["ovt_void_probs"],
                    valid.to(device),things.to(device),m["config"]["eval_size"],1)[0].cpu().numpy()
        else:
            prediction=np.zeros((m["config"]["eval_size"],)*2,np.uint16)
        np.savez_compressed(folder/"prediction.npz",prediction=prediction.astype(np.uint16))
        if args.cache_bundles and result is not None:
            keys=["semantic_slots","visual_memory","ovt_object_valid","raw_rae_hidden"]
            torch.save({k:result[k].detach().cpu() for k in keys},folder/"owner_bundles.pt")
        write_json(folder/"metadata.json",dict(fingerprint=m["fingerprint"],caption_sha256=sample["caption_sha256"],
                   checkpoint=m["config"]["model_path"],inference="image + cached original AR caption; no user request or GT input",
                   all_four_special_token_ids_registered=True,cache_bundles=args.cache_bundles))
        del result
        print(f"Cached image {iid}: {count} AR owners, {len(sample['candidates'])} candidate descriptions.",flush=True)


def select(args):
    import torch
    from transformers import AutoModelForImageTextToText, AutoTokenizer
    root,m=manifest(args)
    by_id={s["image_id"]:s for s in m["samples"]}
    model_path=Path(args.selector_model).resolve()
    if not (model_path/"config.json").is_file():
        raise ValueError("SELECTOR_MODEL must be a pinned local model/snapshot directory")
    torch.set_num_threads(args.cpu_threads)
    torch.manual_seed(args.seed)
    tokenizer=AutoTokenizer.from_pretrained(str(model_path),local_files_only=True)
    spec=dict(fingerprint=m["fingerprint"],condition=args.condition,selector_model=str(model_path),
              model_config_sha256=file_digest(model_path/"config.json"),
              weights_index_sha256=file_digest(model_path/"model.safetensors.index.json"),
              tokenizer_config_sha256=file_digest(model_path/"tokenizer_config.json"),
              system_sha256=digest(SYSTEM),max_new_tokens=args.selector_max_new_tokens,
              max_input_tokens=args.selector_max_input_tokens,do_sample=False,seed=args.seed,
              dtype="bfloat16",image_input=False,gt_input=False)
    key=digest(spec);dest=root/"selections"/args.condition;dest.mkdir(parents=True,exist_ok=True)
    if (dest/"selector_info.json").exists():
        if json.loads((dest/"selector_info.json").read_text())["spec"]!=spec:
            raise ValueError("Existing selector configuration differs; choose a fresh output directory")
    else:
        write_json(dest/"selector_info.json",dict(spec=spec,selection_fingerprint=key))
    pending=[]
    for query in m["queries"]:
        path=dest/"queries"/f"{query['id']}.json"
        if path.exists():
            row=json.loads(path.read_text())
            if row["selection_fingerprint"]!=key or row["query_id"]!=query["id"]:
                raise ValueError("Selection-cache provenance mismatch")
        else:
            pending.append(query)
    if not pending:
        print(f"All {args.condition} selections already cached; no selector model load needed.",flush=True)
        return
    model=AutoModelForImageTextToText.from_pretrained(str(model_path),dtype=torch.bfloat16,
            local_files_only=True).to("cuda").eval()
    info=json.loads((dest/"selector_info.json").read_text())
    info["runtime"]=dict(transformers=__import__("transformers").__version__,torch=torch.__version__,
                          gpu=torch.cuda.get_device_name(0),chat_template_sha256=digest(tokenizer.chat_template))
    write_json(dest/"selector_info.json",info)
    for index,query in enumerate(pending,1):
        sample=by_id[query["image_id"]]
        messages=selector_messages(query["request"],sample["candidates"],args.condition)
        rendered=tokenizer.apply_chat_template(messages,tokenize=False,add_generation_prompt=True)
        inputs=tokenizer(rendered,return_tensors="pt",add_special_tokens=False).to(model.device)
        if inputs["input_ids"].shape[1]>args.selector_max_input_tokens:
            raise ValueError("Selector prompt too long; no silent description truncation")
        started=time.perf_counter()
        if sample["candidates"]:
            with torch.inference_mode():
                output=model.generate(**inputs,max_new_tokens=args.selector_max_new_tokens,do_sample=False)
            raw=tokenizer.decode(output[0,inputs["input_ids"].shape[1]:],skip_special_tokens=True)
            chosen,status=parse_selection(raw,sample["candidates"])
        else:
            raw='{"object_id": null}';chosen,status=None,"no_candidates"
        write_json(dest/"queries"/f"{query['id']}.json",dict(query_id=query["id"],selection_fingerprint=key,
                selected_id=chosen,status=status,raw_completion=raw,prompt_sha256=digest(messages),
                input_tokens=inputs["input_ids"].shape[1],seconds=time.perf_counter()-started))
        print(f"{args.condition} {index}/{len(pending)}: image={sample['image_id']} {chosen} ({status})",flush=True)


def score(args):
    from pgot.eval.class_mask_pairs import masks_for_pairs
    root,m=manifest(args)
    rows={condition:[] for condition in ["category","description","oracle_id"]}
    saved_examples=0
    queries_by_image={}
    for query in m["queries"]:
        queries_by_image.setdefault(query["image_id"],[]).append(query)
    for sample in m["samples"]:
        iid=sample["image_id"]
        if not extracted(root,sample,m["fingerprint"]):
            raise ValueError(f"Owner cache incomplete: {iid}")
        prediction=np.load(root/"owners"/str(iid)/"prediction.npz")["prediction"]
        targets=np.load(root/"gt"/f"{iid}.npz")["targets"]
        mapping,matrix=fixed_correspondence(prediction,sample["candidates"],targets,sample["gt_objects"],m["config"]["presence_iou"])
        for query in queries_by_image.get(iid,[]):
            for condition in rows:
                selection_status="oracle"
                if condition=="oracle_id":
                    selected=mapping.get(str(query["target_segment_id"]))
                else:
                    path=root/"selections"/condition/"queries"/f"{query['id']}.json"
                    if not path.exists():
                        raise ValueError(f"Selection missing; run both conditions before scoring: {path}")
                    selection=json.loads(path.read_text())
                    info=json.loads((root/"selections"/condition/"selector_info.json").read_text())
                    if (info["spec"]["fingerprint"]!=m["fingerprint"] or
                        selection["selection_fingerprint"]!=info["selection_fingerprint"] or
                        selection["query_id"]!=query["id"]):
                        raise ValueError("Selection fingerprint mismatch")
                    selected=selection["selected_id"];selection_status=selection["status"]
                row=score_query(query,selected,sample["candidates"],sample["gt_objects"],matrix,mapping)
                rows[condition].append(dict(row,condition=condition,selection_status=selection_status))
            if saved_examples<args.save_examples:
                original=Image.open(root/"owners"/str(iid)/"image.png").convert("RGB")
                panels=[]
                for condition in rows:
                    row=rows[condition][-1]
                    index=next((i for i,c in enumerate(sample["candidates"]) if c["id"]==row["selected_id"]),None)
                    region=masks_for_pairs(prediction,sample["candidates"])[index] if index is not None else np.zeros(prediction.shape,bool)
                    array=np.asarray(original).copy()
                    array[region]=np.rint(.4*array[region]+.6*np.array([255,60,60])).astype(np.uint8)
                    panel=Image.new("RGB",(original.width,original.height+40),"white")
                    panel.paste(Image.fromarray(array),(0,40))
                    ImageDraw.Draw(panel).text((8,8),f"{condition}: {row['selected_id']} / IoU={row['iou']:.3f}",fill="black")
                    panels.append(panel)
                combined=Image.new("RGB",(sum(p.width for p in panels),panels[0].height),"white")
                for index,panel in enumerate(panels): combined.paste(panel,(index*panel.width,0))
                folder=root/"examples"/query["id"];folder.mkdir(parents=True,exist_ok=True)
                combined.save(folder/"selection_overlay.png")
                original.save(folder/"image.png")
                write_json(folder/"metadata.json",dict(query=query,candidates=sample["candidates"],
                           results={condition:items[-1] for condition,items in rows.items()}))
                saved_examples+=1
    category_info=json.loads((root/"selections/category/selector_info.json").read_text())
    description_info=json.loads((root/"selections/description/selector_info.json").read_text())
    comparable=["selector_model","model_config_sha256","weights_index_sha256","tokenizer_config_sha256",
                "system_sha256","max_new_tokens","max_input_tokens","do_sample","seed","dtype"]
    if any(category_info["spec"][k]!=description_info["spec"][k] for k in comparable):
        raise ValueError("Category/description must use identical selectors and generation settings")
    conditions={condition:aggregate(part) for condition,part in rows.items()}
    summary=dict(version=VERSION,fingerprint=m["fingerprint"],protocol=m["protocol"],conditions=conditions,
                 query_source=m["config"]["query_source"],selector=category_info["spec"],
                 oracle_note="Fixed GT instance correspondence diagnostic, not a deployable selector or a quality guarantee.",
                 invalid_completions={condition:sum(r["selection_status"].startswith("invalid") for r in part) for condition,part in rows.items()})
    write_json(root/"summary.json",summary)
    with (root/"per_query.jsonl").open("w") as stream:
        for condition,part in rows.items():
            for row in part: stream.write(json.dumps(row,ensure_ascii=False,allow_nan=False)+"\n")
    fields=["condition","group","num_queries","present_queries","target_coverage","selection_accuracy_present",
            "selection_accuracy_all","mean_iou","grounding_success_50","grounding_success_75"]
    with (root/"comparison.csv").open("w",newline="") as stream:
        writer=csv.DictWriter(stream,fieldnames=fields);writer.writeheader()
        for condition,groups in conditions.items():
            for group,stats in groups.items(): writer.writerow(dict(condition=condition,group=group,**stats))
    lines=["# Natural-language object selection", "", "Annotation-derived requests; not RefCOCO. Rates are fractions, not percentages.", "",
           "| Input | Queries | Coverage | Selection Acc (present) | Mean IoU | Success@0.5 |", "| --- | ---: | ---: | ---: | ---: | ---: |"]
    fmt=lambda value: "N/A" if value is None else f"{value:.4f}"
    for condition,groups in conditions.items():
        stats=groups["overall"]
        lines.append(f"| {condition} | {stats['num_queries']} | "+" | ".join(fmt(stats[k]) for k in ["target_coverage","selection_accuracy_present","mean_iou","grounding_success_50"])+" |")
    (root/"results.md").write_text("\n".join(lines)+"\n")
    print("\n".join(lines),flush=True)


